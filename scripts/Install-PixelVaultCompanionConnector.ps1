param(
    [Parameter(Mandatory)][string]$PairingFile,
    [string]$PublishedApp='C:\Codex\Companion Preview\connector-0.8.0',
    [string]$InstallRoot='C:\Codex\Companion Connector',
    [string]$DataRoot='C:\Codex\PixelVaultCompanionConnectorData'
)
$ErrorActionPreference='Stop'
$pairingSource=[IO.Path]::GetFullPath($PairingFile)
$connectorPairing=Get-Content -Raw -LiteralPath $pairingSource | ConvertFrom-Json
if($connectorPairing.Token.Length -ne 64 -or $connectorPairing.Sources.Count -lt 1){throw 'Use the private pairing file generated by the NAS.'}
$connectorVersion='0.8.0'
$connectorApp=Join-Path ([IO.Path]::GetFullPath($InstallRoot)) "app-$connectorVersion"
if(Test-Path -LiteralPath $connectorApp){throw 'This connector application directory already exists. Stop the installed connector before updating it.'}
New-Item -ItemType Directory -Path $DataRoot -Force | Out-Null
$connectorOwner=[Security.Principal.WindowsIdentity]::GetCurrent().User
& icacls $DataRoot /inheritance:r /grant:r "*$($connectorOwner.Value):(OI)(CI)F" '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
if($LASTEXITCODE -ne 0){throw 'Could not protect the PC pairing directory.'}
$connectorConfig=Join-Path $DataRoot 'connector.json'
if(Test-Path -LiteralPath $connectorConfig){throw 'A PC pairing already exists. Preserve or revoke it before installing another connection.'}
New-Item -ItemType Directory -Path $connectorApp -Force | Out-Null
Copy-Item -Path (Join-Path $PublishedApp '*') -Destination $connectorApp -Recurse
Copy-Item -LiteralPath $pairingSource -Destination $connectorConfig
$connectorStart=Join-Path $InstallRoot 'Start-Connector.ps1'
@'
$ErrorActionPreference='Stop'
$connectorExe='__APP__\PixelVault.Companion.Connector.exe'
$connectorData='__DATA__'
$connectorPidFile=Join-Path $connectorData 'connector.pid'
if(Test-Path -LiteralPath $connectorPidFile){
    $connectorPrevious=Get-Process -Id ([int](Get-Content -LiteralPath $connectorPidFile)) -ErrorAction SilentlyContinue
    if($connectorPrevious -and $connectorPrevious.Path -eq $connectorExe){return}
}
$connectorProcess=Start-Process -FilePath $connectorExe -ArgumentList ('"'+(Join-Path $connectorData 'connector.json')+'"') -WorkingDirectory (Split-Path $connectorExe -Parent) -WindowStyle Hidden -RedirectStandardOutput (Join-Path $connectorData 'connector.log') -RedirectStandardError (Join-Path $connectorData 'connector-error.log') -PassThru
$connectorProcess.Id | Set-Content -LiteralPath $connectorPidFile
'@.Replace('__APP__',$connectorApp.Replace("'","''")).Replace('__DATA__',([IO.Path]::GetFullPath($DataRoot)).Replace("'","''")) | Set-Content -LiteralPath $connectorStart
$connectorShell=New-Object -ComObject WScript.Shell
$connectorShortcut=$connectorShell.CreateShortcut((Join-Path ([Environment]::GetFolderPath('Startup')) 'PixelVault Companion Connector.lnk'))
$connectorShortcut.TargetPath=(Get-Command pwsh).Source
$connectorShortcut.Arguments='-NoLogo -NoProfile -NonInteractive -WindowStyle Hidden -File "'+$connectorStart+'"'
$connectorShortcut.WorkingDirectory=$InstallRoot
$connectorShortcut.WindowStyle=7
$connectorShortcut.Description='Connect configured read-only PC save sources to PixelVault Companion.'
$connectorShortcut.Save()
& $connectorStart
Write-Host 'PC connection installed and started. It will restart when you sign into Windows.'
